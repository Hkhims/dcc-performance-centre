-- DCC Portal / App
-- Match availability foundation
--
-- Availability is deliberately separate from the existence of a fixture.
--
-- Lifecycle:
--   Fixture exists
--       -> availability Not Open (no poll row)
--       -> Team Admin / Match Admin opens poll
--       -> audience snapshot is created
--       -> players respond Available / Unavailable
--       -> administrator may close the poll
--
-- "Not Responded" is derived:
--   player is in the poll audience
--   AND no response row exists for that player.
--
-- Future fixtures do NOT automatically become availability polls.


-- ============================================================
-- 1. Availability polls
-- ============================================================

create table public.match_availability_polls (
  poll_id bigint generated by default as identity primary key,

  match_id text not null
    references public.matches(match_id)
    on delete cascade,

  team_id text
    references public.teams(team_id)
    on delete cascade,

  status text not null default 'Open',

  opened_at timestamptz not null default now(),

  opened_by uuid not null
    references auth.users(id),

  closed_at timestamptz,

  closed_by uuid
    references auth.users(id),

  created_at timestamptz not null default now(),

  updated_at timestamptz not null default now(),

  constraint match_availability_polls_status_check
    check (status in ('Open', 'Closed')),

  constraint match_availability_polls_close_state_check
    check (
      (
        status = 'Open'
        and closed_at is null
        and closed_by is null
      )
      or
      (
        status = 'Closed'
        and closed_at is not null
        and closed_by is not null
      )
    )
);


-- A normal team fixture may have only one availability poll
-- for that match/team combination.

create unique index match_availability_polls_match_team_unique
  on public.match_availability_polls (
    match_id,
    team_id
  )
  where team_id is not null;


-- An ad-hoc match without a canonical team scope may have
-- only one match-level availability poll.

create unique index match_availability_polls_match_only_unique
  on public.match_availability_polls (match_id)
  where team_id is null;


create index match_availability_polls_match_idx
  on public.match_availability_polls (match_id);


create index match_availability_polls_team_status_idx
  on public.match_availability_polls (
    team_id,
    status
  )
  where team_id is not null;


-- ============================================================
-- 2. Availability audience snapshot
-- ============================================================
--
-- This table records who was actually asked for availability.
--
-- It is intentionally a snapshot.
--
-- If somebody later joins/leaves a team, that must not rewrite
-- the historical audience of an already-opened poll.
-- ============================================================

create table public.match_availability_audience (
  audience_id bigint generated by default as identity primary key,

  poll_id bigint not null
    references public.match_availability_polls(poll_id)
    on delete cascade,

  player_id text not null
    references public.players(player_id),

  added_at timestamptz not null default now(),

  added_by uuid not null
    references auth.users(id),

  created_at timestamptz not null default now(),

  constraint match_availability_audience_poll_player_unique
    unique (poll_id, player_id)
);


create index match_availability_audience_player_idx
  on public.match_availability_audience (player_id);


create index match_availability_audience_poll_idx
  on public.match_availability_audience (poll_id);


-- ============================================================
-- 3. Player responses
-- ============================================================
--
-- Only explicit player choices are stored.
--
-- Stored:
--   Available
--   Unavailable
--
-- NOT stored:
--   Not Responded
--
-- Not Responded = audience member with no response row.
-- ============================================================

create table public.match_availability (
  availability_id bigint generated by default as identity primary key,

  poll_id bigint not null
    references public.match_availability_polls(poll_id)
    on delete cascade,

  player_id text not null
    references public.players(player_id),

  availability_status text not null,

  responded_at timestamptz not null default now(),

  updated_at timestamptz not null default now(),

  constraint match_availability_status_check
    check (
      availability_status in (
        'Available',
        'Unavailable'
      )
    ),

  constraint match_availability_poll_player_unique
    unique (poll_id, player_id)
);


create index match_availability_player_idx
  on public.match_availability (player_id);


create index match_availability_poll_status_idx
  on public.match_availability (
    poll_id,
    availability_status
  );



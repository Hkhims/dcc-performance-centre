-- ============================================================
-- 7. Availability-management authority
-- ============================================================
--
-- A user may administer availability when:
--
--   * they are an active Super Admin; OR
--   * they are an active match-specific admin; OR
--   * for a team-scoped poll, they are an active Team Admin
--     for that team.
--
-- This deliberately does NOT grant authority merely because
-- somebody is a player or availability audience member.
-- ============================================================

create or replace function public.can_manage_match_availability(
  target_match_id text,
  target_team_id text default null
)
returns boolean
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  current_user_id uuid;
  account_is_active boolean := false;
  account_is_super_admin boolean := false;
  is_match_admin boolean := false;
  is_team_admin boolean := false;
begin
  current_user_id := auth.uid();

  if current_user_id is null then
    return false;
  end if;


  select
    true,
    (up.account_role = 'Super Admin')
  into
    account_is_active,
    account_is_super_admin
  from public.user_profiles up
  where up.user_id = current_user_id
    and up.status = 'Active'
  limit 1;


  if not coalesce(account_is_active, false) then
    return false;
  end if;


  if coalesce(account_is_super_admin, false) then
    return true;
  end if;


  select exists (
    select 1
    from public.match_admin_assignments maa
    where maa.match_id = target_match_id
      and maa.user_id = current_user_id
      and maa.active = true
  )
  into is_match_admin;


  if is_match_admin then
    return true;
  end if;


  if target_team_id is not null then

    select exists (
      select 1
      from public.team_admin_assignments taa
      where taa.team_id = target_team_id
        and taa.user_id = current_user_id
        and taa.active = true
    )
    into is_team_admin;


    if is_team_admin then
      return true;
    end if;

  end if;


  return false;
end;
$$;


-- ============================================================
-- 8. Open a team availability poll
-- ============================================================
--
-- For a normal team fixture:
--
--   * Team Admin opens the poll manually.
--   * The team's CURRENT active membership is copied into the
--     availability audience as a snapshot.
--   * Later membership changes do not alter this poll.
--
-- The match must actually be associated with the requested
-- DCC team through match_team_entries.
-- ============================================================

create or replace function public.open_team_match_availability(
  target_match_id text,
  target_team_id text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  new_poll_id bigint;
  target_match_status text;
  team_is_on_match boolean := false;
  active_player_count integer := 0;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_match_id is null
     or btrim(target_match_id) = '' then
    raise exception 'Match ID is required.';
  end if;


  if target_team_id is null
     or btrim(target_team_id) = '' then
    raise exception 'Team ID is required.';
  end if;


  if not public.can_manage_match_availability(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to manage availability for this match.';
  end if;


  select m.status
  into target_match_status
  from public.matches m
  where m.match_id = target_match_id
  for update;


  if not found then
    raise exception 'Match not found.';
  end if;


  if target_match_status <> 'Scheduled' then
    raise exception
      'Availability can only be opened for a scheduled match.';
  end if;


  select exists (
    select 1
    from public.match_team_entries mte
    where mte.match_id = target_match_id
      and mte.team_id = target_team_id
  )
  into team_is_on_match;


  if not team_is_on_match then
    raise exception
      'The selected DCC team is not linked to this match.';
  end if;


  if exists (
    select 1
    from public.match_availability_polls map
    where map.match_id = target_match_id
      and map.team_id = target_team_id
  ) then
    raise exception
      'An availability poll already exists for this match and team.';
  end if;


  select count(*)
  into active_player_count
  from public.team_player_memberships tpm
  join public.players p
    on p.player_id = tpm.player_id
  where tpm.team_id = target_team_id
    and tpm.active = true
    and p.active = true;


  if active_player_count = 0 then
    raise exception
      'This team has no active players available for the poll audience.';
  end if;


  insert into public.match_availability_polls (
    match_id,
    team_id,
    status,
    opened_at,
    opened_by,
    updated_at
  )
  values (
    target_match_id,
    target_team_id,
    'Open',
    now(),
    current_user_id,
    now()
  )
  returning poll_id
  into new_poll_id;


  insert into public.match_availability_audience (
    poll_id,
    player_id,
    added_at,
    added_by
  )
  select
    new_poll_id,
    tpm.player_id,
    now(),
    current_user_id
  from public.team_player_memberships tpm
  join public.players p
    on p.player_id = tpm.player_id
  where tpm.team_id = target_team_id
    and tpm.active = true
    and p.active = true;


  return new_poll_id;
end;
$$;


-- ============================================================
-- 9. Open an ad-hoc/custom availability poll
-- ============================================================
--
-- Some Friendly / Warm-up / Internal matches may not belong
-- naturally to one normal DCC team.
--
-- A match-specific administrator may therefore open a
-- match-level poll and then deliberately build its audience.
--
-- This does NOT apply to Official Season matches.
-- ============================================================

create or replace function public.open_custom_match_availability(
  target_match_id text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  new_poll_id bigint;
  target_match_status text;
  target_stats_category text;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_match_id is null
     or btrim(target_match_id) = '' then
    raise exception 'Match ID is required.';
  end if;


  if not public.can_manage_match_availability(
    target_match_id,
    null
  ) then
    raise exception
      'You do not have permission to manage availability for this match.';
  end if;


  select
    m.status,
    m.stats_category
  into
    target_match_status,
    target_stats_category
  from public.matches m
  where m.match_id = target_match_id
  for update;


  if not found then
    raise exception 'Match not found.';
  end if;


  if target_match_status <> 'Scheduled' then
    raise exception
      'Availability can only be opened for a scheduled match.';
  end if;


  if target_stats_category not in (
    'Friendly',
    'Warm-up',
    'Internal'
  ) then
    raise exception
      'Custom availability polls are only available for Friendly, Warm-up or Internal matches.';
  end if;


  if exists (
    select 1
    from public.match_availability_polls map
    where map.match_id = target_match_id
      and map.team_id is null
  ) then
    raise exception
      'A custom availability poll already exists for this match.';
  end if;


  insert into public.match_availability_polls (
    match_id,
    team_id,
    status,
    opened_at,
    opened_by,
    updated_at
  )
  values (
    target_match_id,
    null,
    'Open',
    now(),
    current_user_id,
    now()
  )
  returning poll_id
  into new_poll_id;


  return new_poll_id;
end;
$$;


-- ============================================================
-- 10. Add a player to an availability audience
-- ============================================================
--
-- Used for:
--   * ad-hoc/custom match audiences;
--   * legitimate additions after a normal poll has opened.
--
-- This does NOT alter permanent team membership.
-- ============================================================

create or replace function public.add_player_to_availability_audience(
  target_poll_id bigint,
  target_player_id text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  target_match_id text;
  target_team_id text;
  target_poll_status text;
  target_player_active boolean := false;
  new_audience_id bigint;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_poll_id is null then
    raise exception 'Poll ID is required.';
  end if;


  if target_player_id is null
     or btrim(target_player_id) = '' then
    raise exception 'Player ID is required.';
  end if;


  select
    map.match_id,
    map.team_id,
    map.status
  into
    target_match_id,
    target_team_id,
    target_poll_status
  from public.match_availability_polls map
  where map.poll_id = target_poll_id
  for update;


  if not found then
    raise exception 'Availability poll not found.';
  end if;


  if target_poll_status <> 'Open' then
    raise exception
      'Players can only be added while the availability poll is open.';
  end if;


  if not public.can_manage_match_availability(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to manage this availability poll.';
  end if;


  select p.active
  into target_player_active
  from public.players p
  where p.player_id = target_player_id;


  if not found then
    raise exception 'Player not found.';
  end if;


  if not coalesce(target_player_active, false) then
    raise exception
      'Only active DCC players can be added to an availability poll.';
  end if;


  if exists (
    select 1
    from public.match_availability_audience maa
    where maa.poll_id = target_poll_id
      and maa.player_id = target_player_id
  ) then
    raise exception
      'This player is already in the availability audience.';
  end if;


  insert into public.match_availability_audience (
    poll_id,
    player_id,
    added_at,
    added_by
  )
  values (
    target_poll_id,
    target_player_id,
    now(),
    current_user_id
  )
  returning audience_id
  into new_audience_id;


  return new_audience_id;
end;
$$;



-- ============================================================
-- 14. Close availability poll
-- ============================================================

create or replace function public.close_match_availability(
  target_poll_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  target_match_id text;
  target_team_id text;
  target_poll_status text;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_poll_id is null then
    raise exception 'Poll ID is required.';
  end if;


  select
    map.match_id,
    map.team_id,
    map.status
  into
    target_match_id,
    target_team_id,
    target_poll_status
  from public.match_availability_polls map
  where map.poll_id = target_poll_id
  for update;


  if not found then
    raise exception 'Availability poll not found.';
  end if;


  if not public.can_manage_match_availability(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to manage this availability poll.';
  end if;


  if target_poll_status = 'Closed' then
    raise exception
      'This availability poll is already closed.';
  end if;


  update public.match_availability_polls
  set
    status = 'Closed',
    closed_at = now(),
    closed_by = current_user_id,
    updated_at = now()
  where poll_id = target_poll_id;
end;
$$;


-- ============================================================
-- 15. Re-open availability poll
-- ============================================================
--
-- Real cricket changes.
--
-- A Team Admin may need to re-open a poll after somebody drops
-- out, a match is rearranged, etc.
--
-- Existing audience and responses are preserved.
-- ============================================================

create or replace function public.reopen_match_availability(
  target_poll_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  target_match_id text;
  target_team_id text;
  target_poll_status text;
  target_match_status text;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_poll_id is null then
    raise exception 'Poll ID is required.';
  end if;


  select
    map.match_id,
    map.team_id,
    map.status
  into
    target_match_id,
    target_team_id,
    target_poll_status
  from public.match_availability_polls map
  where map.poll_id = target_poll_id
  for update;


  if not found then
    raise exception 'Availability poll not found.';
  end if;


  if not public.can_manage_match_availability(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to manage this availability poll.';
  end if;


  if target_poll_status = 'Open' then
    raise exception
      'This availability poll is already open.';
  end if;


  select m.status
  into target_match_status
  from public.matches m
  where m.match_id = target_match_id;


  if not found then
    raise exception 'Match not found.';
  end if;


  if target_match_status <> 'Scheduled' then
    raise exception
      'Availability can only be re-opened while the match is scheduled.';
  end if;


  update public.match_availability_polls
  set
    status = 'Open',
    closed_at = null,
    closed_by = null,
    updated_at = now()
  where poll_id = target_poll_id;
end;
$$;



-- ============================================================
-- 12. Submit / change MY availability
-- ============================================================
--
-- Important security rule:
--
-- The client does NOT supply a player_id.
--
-- We derive the player from:
--
--   auth.uid()
--       -> user_profiles
--       -> player_id
--
-- Therefore a player cannot use this RPC to submit availability
-- on behalf of somebody else.
--
-- Re-submitting changes the same response row.
-- ============================================================

create or replace function public.set_my_match_availability(
  target_poll_id bigint,
  target_availability_status text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  current_player_id text;
  target_poll_status text;
  resulting_availability_id bigint;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_poll_id is null then
    raise exception 'Poll ID is required.';
  end if;


  if target_availability_status not in (
    'Available',
    'Unavailable'
  ) then
    raise exception
      'Availability must be Available or Unavailable.';
  end if;


  select up.player_id
  into current_player_id
  from public.user_profiles up
  where up.user_id = current_user_id
    and up.status = 'Active'
  limit 1;


  if current_player_id is null then
    raise exception
      'Your active DCC account is not linked to a player.';
  end if;


  if not exists (
    select 1
    from public.players p
    where p.player_id = current_player_id
      and p.active = true
  ) then
    raise exception
      'Your linked DCC player is not active.';
  end if;


  select map.status
  into target_poll_status
  from public.match_availability_polls map
  where map.poll_id = target_poll_id
  for update;


  if not found then
    raise exception 'Availability poll not found.';
  end if;


  if target_poll_status <> 'Open' then
    raise exception
      'This availability poll is not open.';
  end if;


  if not exists (
    select 1
    from public.match_availability_audience maa
    where maa.poll_id = target_poll_id
      and maa.player_id = current_player_id
  ) then
    raise exception
      'You are not in the availability audience for this match.';
  end if;


  insert into public.match_availability (
    poll_id,
    player_id,
    availability_status,
    responded_at,
    updated_at
  )
  values (
    target_poll_id,
    current_player_id,
    target_availability_status,
    now(),
    now()
  )
  on conflict (poll_id, player_id)
  do update
  set
    availability_status = excluded.availability_status,
    responded_at = now(),
    updated_at = now()
  returning availability_id
  into resulting_availability_id;


  return resulting_availability_id;
end;
$$;



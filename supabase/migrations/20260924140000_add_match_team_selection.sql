-- ============================================================
-- 6. Selection-management authority
-- ============================================================
--
-- Authority:
--
--   * active Super Admin; OR
--   * active match-specific admin; OR
--   * active Team Admin for the selected DCC team.
-- ============================================================

create or replace function public.can_manage_match_selection(
  target_match_id text,
  target_team_id text
)
returns boolean
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  current_user_id uuid;
  account_is_active boolean := false;
  account_is_super_admin boolean := false;
  is_match_admin boolean := false;
  is_team_admin boolean := false;
begin
  current_user_id := auth.uid();

  if current_user_id is null then
    return false;
  end if;


  select
    true,
    (up.account_role = 'Super Admin')
  into
    account_is_active,
    account_is_super_admin
  from public.user_profiles up
  where up.user_id = current_user_id
    and up.status = 'Active'
  limit 1;


  if not coalesce(account_is_active, false) then
    return false;
  end if;


  if coalesce(account_is_super_admin, false) then
    return true;
  end if;


  select exists (
    select 1
    from public.match_admin_assignments maa
    where maa.match_id = target_match_id
      and maa.user_id = current_user_id
      and maa.active = true
  )
  into is_match_admin;


  if is_match_admin then
    return true;
  end if;


  select exists (
    select 1
    from public.team_admin_assignments taa
    where taa.team_id = target_team_id
      and taa.user_id = current_user_id
      and taa.active = true
  )
  into is_team_admin;


  return is_team_admin;
end;
$$;


-- ============================================================
-- 7. Create / obtain draft selection
-- ============================================================

create or replace function public.create_match_selection(
  target_match_id text,
  target_team_id text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  target_match_status text;
  team_is_on_match boolean := false;
  existing_selection_id bigint;
  new_selection_id bigint;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_match_id is null
     or btrim(target_match_id) = '' then
    raise exception 'Match ID is required.';
  end if;


  if target_team_id is null
     or btrim(target_team_id) = '' then
    raise exception 'Team ID is required.';
  end if;


  if not public.can_manage_match_selection(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to manage selection for this match.';
  end if;


  select m.status
  into target_match_status
  from public.matches m
  where m.match_id = target_match_id
  for update;


  if not found then
    raise exception 'Match not found.';
  end if;


  if target_match_status <> 'Scheduled' then
    raise exception
      'Team selection can only be created for a scheduled match.';
  end if;


  select exists (
    select 1
    from public.match_team_entries mte
    where mte.match_id = target_match_id
      and mte.team_id = target_team_id
  )
  into team_is_on_match;


  if not team_is_on_match then
    raise exception
      'The selected DCC team is not linked to this match.';
  end if;


  select ms.selection_id
  into existing_selection_id
  from public.match_selections ms
  where ms.match_id = target_match_id
    and ms.team_id = target_team_id
  limit 1;


  if existing_selection_id is not null then
    return existing_selection_id;
  end if;


  insert into public.match_selections (
    match_id,
    team_id,
    status,
    created_by,
    created_at,
    updated_by,
    updated_at
  )
  values (
    target_match_id,
    target_team_id,
    'Draft',
    current_user_id,
    now(),
    current_user_id,
    now()
  )
  returning selection_id
  into new_selection_id;


  return new_selection_id;
end;
$$;


-- ============================================================
-- 8. Add player to selection
-- ============================================================

create or replace function public.add_player_to_match_selection(
  target_selection_id bigint,
  target_player_id text,
  target_batting_position integer default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  target_match_id text;
  target_team_id text;
  target_selection_status text;
  target_player_active boolean := false;
  new_selection_player_id bigint;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  if target_selection_id is null then
    raise exception 'Selection ID is required.';
  end if;


  if target_player_id is null
     or btrim(target_player_id) = '' then
    raise exception 'Player ID is required.';
  end if;


  if target_batting_position is not null
     and target_batting_position < 1 then
    raise exception
      'Batting position must be 1 or greater.';
  end if;


  select
    ms.match_id,
    ms.team_id,
    ms.status
  into
    target_match_id,
    target_team_id,
    target_selection_status
  from public.match_selections ms
  where ms.selection_id = target_selection_id
  for update;


  if not found then
    raise exception 'Match selection not found.';
  end if;


  if target_selection_status <> 'Draft' then
    raise exception
      'Only a draft selection can be edited.';
  end if;


  if not public.can_manage_match_selection(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to manage this selection.';
  end if;


  select p.active
  into target_player_active
  from public.players p
  where p.player_id = target_player_id;


  if not found then
    raise exception 'Player not found.';
  end if;


  if not coalesce(target_player_active, false) then
    raise exception
      'Only active DCC players can be selected.';
  end if;


  if exists (
    select 1
    from public.match_selection_players msp
    where msp.selection_id = target_selection_id
      and msp.player_id = target_player_id
  ) then
    raise exception
      'This player is already in the selection.';
  end if;


  if target_batting_position is not null
     and exists (
       select 1
       from public.match_selection_players msp
       where msp.selection_id = target_selection_id
         and msp.batting_position = target_batting_position
     ) then
    raise exception
      'That batting position is already assigned.';
  end if;


  insert into public.match_selection_players (
    selection_id,
    player_id,
    batting_position,
    is_captain,
    is_wicketkeeper,
    added_at,
    added_by,
    updated_at,
    updated_by
  )
  values (
    target_selection_id,
    target_player_id,
    target_batting_position,
    false,
    false,
    now(),
    current_user_id,
    now(),
    current_user_id
  )
  returning selection_player_id
  into new_selection_player_id;


  update public.match_selections
  set
    updated_by = current_user_id,
    updated_at = now()
  where selection_id = target_selection_id;


  return new_selection_player_id;
end;
$$;



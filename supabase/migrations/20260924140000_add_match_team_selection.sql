-- ============================================================
-- 13. Publish selection
-- ============================================================
--
-- Publication deliberately does NOT check availability.
--
-- It also deliberately does not require exactly 11 players.
-- Real cricket can involve reduced teams, unusual formats and
-- administrative corrections.
--
-- A captain and wicketkeeper ARE required before publication.
-- ============================================================

create or replace function public.publish_match_selection(
  target_selection_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  target_match_id text;
  target_team_id text;
  target_selection_status text;
  target_match_status text;
  selected_player_count integer;
  captain_count integer;
  wicketkeeper_count integer;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  select
    ms.match_id,
    ms.team_id,
    ms.status
  into
    target_match_id,
    target_team_id,
    target_selection_status
  from public.match_selections ms
  where ms.selection_id = target_selection_id
  for update;


  if not found then
    raise exception 'Match selection not found.';
  end if;


  if target_selection_status <> 'Draft' then
    raise exception
      'Only a draft selection can be published.';
  end if;


  if not public.can_manage_match_selection(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to publish this selection.';
  end if;


  select m.status
  into target_match_status
  from public.matches m
  where m.match_id = target_match_id;


  if not found then
    raise exception 'Match not found.';
  end if;


  if target_match_status <> 'Scheduled' then
    raise exception
      'Selection can only be published while the match is scheduled.';
  end if;


  select
    count(*),
    count(*) filter (where msp.is_captain = true),
    count(*) filter (where msp.is_wicketkeeper = true)
  into
    selected_player_count,
    captain_count,
    wicketkeeper_count
  from public.match_selection_players msp
  where msp.selection_id = target_selection_id;


  if selected_player_count = 0 then
    raise exception
      'At least one player must be selected before publication.';
  end if;


  if captain_count <> 1 then
    raise exception
      'Exactly one selected player must be designated captain.';
  end if;


  if wicketkeeper_count <> 1 then
    raise exception
      'Exactly one selected player must be designated wicketkeeper.';
  end if;


  update public.match_selections
  set
    status = 'Published',
    published_by = current_user_id,
    published_at = now(),
    updated_by = current_user_id,
    updated_at = now()
  where selection_id = target_selection_id;
end;
$$;


-- ============================================================
-- 14. Return published selection to Draft
-- ============================================================
--
-- Real cricket changes.
--
-- Somebody may drop out after the XI has been published.
-- An authorised administrator can return it to Draft, edit it,
-- and publish again.
-- ============================================================

create or replace function public.reopen_match_selection(
  target_selection_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid;
  target_match_id text;
  target_team_id text;
  target_selection_status text;
  target_match_status text;
begin
  current_user_id := auth.uid();


  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;


  select
    ms.match_id,
    ms.team_id,
    ms.status
  into
    target_match_id,
    target_team_id,
    target_selection_status
  from public.match_selections ms
  where ms.selection_id = target_selection_id
  for update;


  if not found then
    raise exception 'Match selection not found.';
  end if;


  if not public.can_manage_match_selection(
    target_match_id,
    target_team_id
  ) then
    raise exception
      'You do not have permission to manage this selection.';
  end if;


  if target_selection_status <> 'Published' then
    raise exception
      'Only a published selection can be returned to Draft.';
  end if;


  select m.status
  into target_match_status
  from public.matches m
  where m.match_id = target_match_id;


  if not found then
    raise exception 'Match not found.';
  end if;


  if target_match_status <> 'Scheduled' then
    raise exception
      'Selection can only be changed while the match is scheduled.';
  end if;


  update public.match_selections
  set
    status = 'Draft',
    published_by = null,
    published_at = null,
    updated_by = current_user_id,
    updated_at = now()
  where selection_id = target_selection_id;
end;
$$;



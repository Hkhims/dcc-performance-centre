-- DCC Portal / App
-- Match team-selection foundation
--
-- Core principle:
--   Availability informs selection but never controls it.
--
-- A Team Admin / Match Admin may create and publish a selection
-- whether:
--   * no availability poll exists;
--   * availability is Open;
--   * availability is Closed;
--   * a selected player responded Available;
--   * a selected player responded Unavailable; or
--   * a selected player did not respond.
--
-- Selection is therefore an independent match workflow.


-- ============================================================
-- 1. Match selections
-- ============================================================

create table public.match_selections (
  selection_id bigint generated by default as identity primary key,

  match_id text not null
    references public.matches(match_id)
    on delete cascade,

  team_id text not null
    references public.teams(team_id),

  status text not null default 'Draft',

  created_by uuid not null
    references auth.users(id),

  created_at timestamptz not null default now(),

  updated_by uuid not null
    references auth.users(id),

  updated_at timestamptz not null default now(),

  published_by uuid
    references auth.users(id),

  published_at timestamptz,

  constraint match_selections_status_check
    check (status in ('Draft', 'Published')),

  constraint match_selections_publish_state_check
    check (
      (
        status = 'Draft'
        and published_by is null
        and published_at is null
      )
      or
      (
        status = 'Published'
        and published_by is not null
        and published_at is not null
      )
    ),

  constraint match_selections_match_team_unique
    unique (match_id, team_id)
);


create index match_selections_team_status_idx
  on public.match_selections (
    team_id,
    status
  );


create index match_selections_match_idx
  on public.match_selections (match_id);


-- ============================================================
-- 2. Selected players
-- ============================================================
--
-- No foreign-key relationship to team_player_memberships exists
-- deliberately.
--
-- A player does NOT need to be a normal member of this team to
-- be selected for this particular match.
--
-- Likewise, no availability response is required.
-- ============================================================

create table public.match_selection_players (
  selection_player_id bigint generated by default as identity primary key,

  selection_id bigint not null
    references public.match_selections(selection_id)
    on delete cascade,

  player_id text not null
    references public.players(player_id),

  batting_position integer,

  is_captain boolean not null default false,

  is_wicketkeeper boolean not null default false,

  added_at timestamptz not null default now(),

  added_by uuid not null
    references auth.users(id),

  updated_at timestamptz not null default now(),

  updated_by uuid not null
    references auth.users(id),

  constraint match_selection_players_unique
    unique (selection_id, player_id),

  constraint match_selection_players_batting_position_check
    check (
      batting_position is null
      or batting_position >= 1
    )
);


create unique index match_selection_one_batting_position
  on public.match_selection_players (
    selection_id,
    batting_position
  )
  where batting_position is not null;


create unique index match_selection_one_captain
  on public.match_selection_players (selection_id)
  where is_captain = true;


create unique index match_selection_one_wicketkeeper
  on public.match_selection_players (selection_id)
  where is_wicketkeeper = true;


create index match_selection_players_player_idx
  on public.match_selection_players (player_id);


